# ## 0. 요약

# **프레이밍 전환:** "4개 회랑이 지정되어 있다"는 전제를 버립니다. 대신 **"회랑 기반 공공 프로그램이 새로 도입된다면, 회랑을 어떻게 지정하든 어떤 역이 구조적으로 누락되는가"**를 묻습니다. 이렇게 하면 정책 문서 요구(R1-1, R2-1, R3-1)에 방어 부담이 사라집니다. 동시에 논문의 기여가 "알려진 도구의 한국 적용"에서 **"scope 설계 공간 전체에 대한 감사와 설계에 무관한 사각지대 식별"**로 올라갑니다.

# **지금까지의 핵심 발견 3가지**
# 1. demand/utilization은 실측 화물량이 아니라 운행빈도의 선형변환입니다.
# 2. 53노드 네트워크는 선로망이 아니라 **열차 서비스 연결망**입니다.
# 3. 논문 1순위 역인 오봉은 scope 정의에 따라 판정이 갈립니다. 이 발견이 새 프레이밍의 출발점이 됩니다.

