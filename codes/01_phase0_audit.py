# ### Phase 1. 회랑 설계 공간 구축 (새 중심축)

# 1. **회랑 단위 정의:** `main_line_kor`의 고유 노선 집합 L을 확정합니다. 노선별 열차 수, 주간 열차-일, 열차-km(열차-일 × `distance_km`)를 집계합니다.
# 2. **역별 커버리지 가중치(주 정의)**
#    - 회랑 집합 S가 지정되면 역 i의 커버 w_i(S)는 **그 역에서 출발·도착하는 열차-일 중 S에 속한 노선의 비율**로 정의합니다.
#    - 이 정의가 더 자연스러운 이유는 회랑 지정 프로그램이 노선 위의 서비스를 대상으로 하기 때문입니다. 오봉 같은 지선 단말 역이 단일 태그(`남부화물`) 때문에 자동으로 범위 밖이 되는 인위성도 사라집니다.
#    - **사전 등록의 한계:** 이 정의 선택은 오봉 문제를 본 뒤에 이루어졌습니다. 분기점 선택의 자유도가 있었다는 사실을 투고 문서에 투명하게 쓰고, 아래 3번의 명세 곡선으로 보완합니다.
# 3. **설계 공간 열거:** |L|이 12 안팎이면 크기 m(예: 2~6)의 모든 부분집합이 최대 수천 개이므로 **전수 열거**합니다. 연속성 제약(회랑이 서로 연결되는 조합만)과 무제약을 둘 다 계산합니다.
# 4. **명세 곡선(specification curve):** 가중치 정의(서비스 기준, 노선 태그 기준, 분기선→본선), 후보풀 임계값, 가치 지표(아래 Phase 2) 조합의 결과를 한 그림에 모아, 결론이 정의 선택에 얼마나 의존하는지 직접 보여줍니다. 주 분석을 고르는 자유도를 오히려 결과의 일부로 만드는 방식입니다.
# 5. **기준 시나리오 정의:** "열차-km 상위 m개 노선"을 사전에 확정하고, 이 조합이 설계 공간에서 어디에 위치하는지(OCG 분위, 커버 가치 순위)를 보고합니다. 원래 4개 회랑과의 일치 여부는 결과로만 언급합니다.

# ### Phase 2. Stage A–B 재설계 (집중도 진단)

# 1. **가치 지표 3종을 병렬로 둡니다.**
