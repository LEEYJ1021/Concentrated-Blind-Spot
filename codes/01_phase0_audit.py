#    - (c) 경험분포를 보존하는 재표집을 사용합니다.
# 4. **in-scope 대조:** 집중이 범위 밖에서만 나타나는지, 네트워크 전체의 성질인지 Gini 차이로 검정합니다. 전체가 집중돼 있다면 "범위 밖 집중"은 자명한 결과이므로 이 구분이 논문의 신뢰성을 좌우합니다.
# 5. **불확실성의 재정의:** 53개 역은 표본이 아니라 전수입니다. 역 단위 bootstrap 대신 열차 단위 재표집, 운행일수 교란, 엣지 jackknife를 쓰고 매번 중심성을 **재계산**합니다.
# 6. **다중검정:** 확증 검정군을 명시하고 Holm 적용 위치를 정합니다. 시뮬레이션 p는 MC 오차와 함께 보고합니다.

# ### Phase 3. 설계 불변 사각지대 분석 (C2의 핵심)

# 1. **DIBI 정의(사전 등록):** 역 i에 대해, 설계 공간의 각 지정 S에서 w_i(S) < τ인 비율 q_i와, 구조 가치 v_i(순위 기반 정규화)의 결합 지표를 정의합니다. 예: DIBI_i = q_i × v_i. τ는 민감도로 둡니다.
# 2. **불변 사각지대:** q_i가 높고 v_i도 높은 역(어떤 지정 방식에서도 누락되기 쉬운 고가치 역)을 식별합니다. 이것이 정책 문서 없이도 방어되는 핵심 결과입니다.
# 3. **추가 정보 검증:** DIBI 순위가 (i) 중심성 단순 순위, (ii) 기준 시나리오 단독 결과와 얼마나 다른지 순위 상관과 top-k 차이로 보고합니다. 차이가 작다면 DIBI의 한계를 명시하고 기여 주장을 낮춥니다.
# 4. **파레토 프런티어:** 지정 회랑 수(비용 대리)에 대해 커버 가치를 최대화하는 조합을 구하고, 기준 시나리오가 프런티어에서 얼마나 떨어져 있는지 보고합니다.
# 5. **설계 선택의 민감도:** 어떤 노선 하나를 추가·제거할 때 사각지대 가치가 가장 크게 변하는 "한계 회랑"을 식별합니다. 정책 설계자에게 실질적 시사점이 됩니다.

# ### Phase 4. Stage C 재구축 (처방)

# 1. **목적함수 완전 명세:** f(S), 정규화, 중첩 할인 규칙, 시나리오 분포를 모두 적습니다. 단조성과 서브모듈성은 증명하거나 수치로 검증하고, 성립하지 않으면 (1−1/e) 보장을 철회합니다. 쌍별 할인을 단순히 빼는 형태는 단조성을 잃을 수 있습니다.
# 2. **정확해 비교:** C(34,5)=278,256이므로 전수 열거로 최적해와 greedy를 직접 비교합니다. 후보풀은 Phase 1의 기준 시나리오 하에서 정합니다.
# 3. **벤치마크:** Stage B top-5, 개별 특징 top-5, 중첩 보정 없는 합성 점수 top-5, 무작위를 같은 후보군·목적함수로 평가합니다.
# 4. **K 스윕(1~15):** 한계이득 곡선을 그립니다.
# 5. **비용 가중 버전:** 역상세의 야드 선로 길이, 선수를 비용 대리변수로 쓰는 knapsack 버전을 추가합니다. 53개 중 몇 개 역이 이 변수를 가졌는지 먼저 확인해야 합니다. 부족하면 균일 비용으로 두고, cardinality 제약이 예산 제약이 아님을 명시합니다.
# 6. **입력 재구성:** demand/utilization은 빈도의 선형변환이므로 폐기하고, 서비스 열차-km와 재계산한 closeness·eigenvector 위주로 구성합니다. 특약 경유 건수는 보조로 씁니다. closeness+eigenvector 단독 버전과 전체 버전을 모두 제시합니다.
# 7. **H3 재검정**
#    - 의존성 감사를 **실제 Stage B 지표**에 대해 수행합니다.
#    - 정확 초기하분포(P(X≥4)=146/278,256≈0.000525)를 쓰고, 20,000회 시뮬레이션은 MC 오차와 함께 보고하거나 폐기합니다.
#    - 공유 정보를 반영한 조건부 귀무(Stage B 점수와 같은 상관을 갖는 잡음 점수의 top-5)를 추가합니다.
# 8. **안정성:** 가중치 분포를 명시하고, 역별 선택빈도와 정확 집합 재현율을 구분해 "조건부 민감도"로 서술합니다.

# ### Phase 5. 공간분석 재설계

# 1. Moran's I를 기대값 −1/(N−1)(N=34이면 −0.0303)과 비교하고, z값과 p를 k=3~8 **전부(7 포함)** 보고합니다.
# 2. 가중치를 3종 병행합니다. 지리적 k-NN(대원거리), 역거리, **서비스 엣지 연결 기반 이진 가중치**(R2-11의 지리 이웃 vs 철도 이웃).
# 3. 국지 분석(LISA, Getis-Ord Gi*)과 상위 지표의 최근접 이웃 지수를 추가합니다.
# 4. **검정력 분석:** 사전에 정의한 군집 시나리오를 주입해 탐지율을 계산합니다. 사후 관측 검정력은 쓰지 않습니다.
# 5. **C3의 직접 비교:** "역 단위 추가 K개 vs 회랑 1개 추가"를 같은 커버 역 수 또는 비용 대리변수 기준으로 비교합니다. 이 결과가 정책 비교의 핵심 증거입니다.
# 6. 서술은 "전역 군집 미검출"로 쓰고 "분산"이라는 표현은 쓰지 않습니다.
# 7. 한계: 대원거리와 서비스 연결 기반이므로 **선로 거리 기반 분석은 수행하지 않았음**을 본문에 명시합니다.

# ### Phase 6. H2와 다층 검증

# 1. **재배선 1,000회 이상:** MC 오차를 p=0.05 근방에서 사전에 계산해 크기를 정당화합니다. 통계량과 모집단을 메인 분석과 같게 고정하고, 0값 역은 필터링하지 않고 처리 규칙을 명시합니다.
