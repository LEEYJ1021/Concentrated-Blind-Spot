# 3. **H2의 재진술:** "기전"이 아니라 "다른 네트워크 실현에서도 관측값이 비정상적인가"로 바꾸고, 분포 안에서 관측값의 순위를 직접 보고합니다.
# 4. **외생 검증(C4)**
#    - 랭킹 구성에 쓰지 않은 데이터로 검증합니다. 예약 신청 대비 적재 완료율, 적하 조정 이벤트(복구된 파일 기준), 특약 경유 건수가 후보입니다.
